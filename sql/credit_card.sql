SELECT SK_ID_CURR,
  COUNT(*)                                                         AS CC_RECORD_COUNT,
  AVG(AMT_BALANCE / NULLIF(AMT_CREDIT_LIMIT_ACTUAL, 0))            AS AVERAGE_CREDIT_UTILIZATION,
  MAX(AMT_BALANCE / NULLIF(AMT_CREDIT_LIMIT_ACTUAL, 0))            AS MAX_CREDIT_UTILIZATION,
  MAX(SK_DPD)                                                      AS CC_DPD_MAX,
  AVG(AMT_DRAWINGS_CURRENT)                                        AS CC_DRAWINGS_MEAN,
  SUM(AMT_PAYMENT_CURRENT) / NULLIF(SUM(AMT_DRAWINGS_CURRENT), 0)  AS CC_PAYMENT_DRAWINGS_RATIO
FROM credit_card_balance WHERE MONTHS_BALANCE <= 0 GROUP BY SK_ID_CURR
